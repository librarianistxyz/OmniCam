"""
Digital Gimbal Horizon Stabilization for OmniCam
Smooths handheld wobble, walking bounce, and camera tilt using 2-pass optical motion stabilization.
"""

import os
import subprocess
import tempfile
from typing import Callable, Optional


def is_vidstab_supported() -> bool:
    """Checks if the local FFmpeg installation has libvidstab enabled."""
    try:
        res = subprocess.run(["ffmpeg", "-filters"], capture_output=True, text=True)
        return "vidstabdetect" in res.stdout and "vidstabtransform" in res.stdout
    except Exception:
        return False


class VideoStabilizer:
    """
    Two-pass optical motion stabilizer that acts as a digital gimbal (DJI Ronin effect).
    Pass 1 computes camera movement vectors and rotation matrices.
    Pass 2 applies Gaussian path smoothing to neutralize tremors and walking sway.
    """

    def __init__(
        self,
        shakiness: int = 8,
        accuracy: int = 15,
        smoothing: int = 25,
        stepsize: int = 6,
    ):
        self.shakiness = shakiness
        self.accuracy = accuracy
        self.smoothing = smoothing
        self.stepsize = stepsize

    def detect_transforms(
        self,
        video_path: str,
        trf_output_path: str,
        progress_callback: Optional[Callable[[float, str], None]] = None,
    ) -> str:
        """Pass 1: Analyzes relative frame transformations and writes transforms.trf."""
        if not is_vidstab_supported():
            raise RuntimeError("FFmpeg does not have libvidstab (vidstabdetect) compiled in.")

        video_path = os.path.abspath(video_path)
        trf_output_path = os.path.abspath(trf_output_path)
        os.makedirs(os.path.dirname(trf_output_path) or ".", exist_ok=True)

        if progress_callback:
            progress_callback(0.05, "Digital Gimbal: Scanning frame trajectory & tremors (Pass 1/2)...")

        escaped_trf = trf_output_path.replace("\\", "/").replace(":", "\\:")
        detect_filter = (
            f"vidstabdetect=stepsize={self.stepsize}:shakiness={self.shakiness}:"
            f"accuracy={self.accuracy}:result='{escaped_trf}'"
        )

        cmd = [
            "ffmpeg",
            "-y",
            "-hide_banner",
            "-loglevel", "error",
            "-i", video_path,
            "-vf", detect_filter,
            "-f", "null",
            "-",
        ]

        res = subprocess.run(cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"Gimbal stabilization Pass 1 failed: {res.stderr[-500:]}")

        if not os.path.isfile(trf_output_path) or os.path.getsize(trf_output_path) == 0:
            raise RuntimeError("Transforms file was not generated by vidstabdetect.")

        if progress_callback:
            progress_callback(0.15, "Digital Gimbal: Trajectory mapped. Preparing gimbal transform...")

        return trf_output_path

    def get_transform_filter(self, trf_path: str) -> str:
        """Returns the Pass 2 FFmpeg filter string for applying smooth gimbal transform."""
        escaped_trf = trf_path.replace("\\", "/").replace(":", "\\:")
        return (
            f"vidstabtransform=input='{escaped_trf}':smoothing={self.smoothing}:"
            f"optalgo=gauss:interpol=bicubic:zoom=2:crop=black"
        )
